"""Read-only committed-tree and local payload freeze check. No run, RPC or network."""
from pathlib import Path
import hashlib
import json
import subprocess

ROOT = Path(__file__).resolve().parents[2]
EXCLUDED = {'sdk/src/constants.local.ts'}  # Regenerated by the deployer.


def git(*args):
    return subprocess.check_output(['git', '-C', str(ROOT), *args])


def aggregate(files):
    return hashlib.sha256(json.dumps(files, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def safe(name):
    parts = Path(name).parts
    assert not any(p.startswith('.env') or 'secret' in p.lower() or 'key' in p.lower()
                   and Path(p).suffix in {'.pem', '.key', '.p12'} for p in parts), 'sensitive path rejected'


def committed_files(ref, prefix):
    names = git('ls-tree', '-r', '--name-only', ref, '--', prefix).decode().splitlines()
    result = {}
    for name in names:
        safe(name)
        if name not in EXCLUDED:
            result[name] = hashlib.sha256(git('show', f'{ref}:{name}')).hexdigest()
    return result


def tree(ref, prefix):
    files = {p[len(prefix) + 1:]: h for p, h in committed_files(ref, prefix).items()}
    assert files, f'empty committed tree: {prefix}'
    return dict(files=files, sha256=aggregate(files))


def verify():
    lock = json.loads((ROOT / 'ascon-notes/league/q-zeta-02-lock.json').read_text())
    assert lock['excludedFromHashing'] == sorted(EXCLUDED)
    pairs = [('example/agents/ascon-zeta-r2', lock['candidate']),
             ('example/agents/ascon-zeta-r', lock['predecessor']),
             ('example/agents/ascon-zeta', lock['original'])]
    pairs += [('example/agents/' + n, t) for n, t in lock['references'].items()]
    for prefix, expected in pairs:
        assert tree(lock['sourceHead'], prefix) == expected, f'source tree drift: {prefix}'
        assert tree('HEAD', prefix) == expected, f'committed HEAD drift: {prefix}'
        local = {}
        for p in sorted((ROOT / prefix).rglob('*')):
            if p.is_file():
                safe(p.relative_to(ROOT).as_posix())
                local[p.relative_to(ROOT / prefix).as_posix()] = hashlib.sha256(p.read_bytes()).hexdigest()
        assert local == expected['files'], f'working tree drift: {prefix}'
    assert tree(lock['candidateCommit'], 'example/agents/ascon-zeta-r2') == lock['candidate']
    actual = {}
    for prefix in lock['committedHashScopes']:
        actual.update(committed_files('HEAD', prefix))
    assert actual == lock['runtimeAndEvaluationFiles'], 'committed dependency/runner drift'
    assert aggregate(actual) == lock['runtimeAndEvaluationSha256']
    for name, expected in actual.items():
        assert hashlib.sha256((ROOT / name).read_bytes()).hexdigest() == expected, f'local dependency drift: {name}'
    for name, expected in lock['artifactFiles'].items():
        assert hashlib.sha256((ROOT / name).read_bytes()).hexdigest() == expected, f'artifact drift: {name}'
    contract = (ROOT / 'ascon-notes/league/Q-ZETA-02.md').read_text()
    old = (ROOT / 'ascon-notes/league/Q-ZETA-01.md').read_text()
    criteria = lambda s: s.split('## 3. 合格条件 — 全て必要、変更しない\n', 1)[1].split('\n比較対象', 1)[0]
    assert criteria(contract) == criteria(old), 'qualification criteria changed'
    assert lock['candidate']['sha256'] in contract
    assert lock['runtimeAndEvaluationSha256'] in contract
    assert lock['seedProposal'] == list(range(47001, 47006))
    assert lock['attemptLimit'] == 1 and lock['worlds'] == 60
    assert lock['status'] == 'registered-pending-start'
    assert '| 実行担当Claudeの開始前照合 |' in contract, 'missing executor verification row'
    print(json.dumps(dict(status='PASS', candidateSha256=lock['candidate']['sha256'],
                         files=len(actual), verification='committed HEAD + working tree; generated constants excluded',
                         note='Not G0, host selection, budget settlement or qualification.')))


if __name__ == '__main__':
    verify()
